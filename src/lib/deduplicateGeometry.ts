/**
 * deduplicateGeometry.ts - 同一道路の重複描画を排除するユーティリティ
 *
 * ─── なぜ2本線が表示されるのか ──────────────────────────────────
 *
 *  OSRM は道路を「エッジ（辺）」の集まりとして管理している。
 *  幹線道路など中央分離帯がある道路（=双方向2車線以上）は、
 *  OSM データ上で「上り車線の道」と「下り車線の道」が別々の Way として
 *  登録されていることがある。
 *
 *  例: 国道1号線
 *    ・Way #123456  → 東行き車線（A→B）
 *    ・Way #123457  → 西行き車線（B→A）
 *
 *  OSRM がルートを計算すると、行きは Way #123456 を使い、
 *  帰りは Way #123457 を使う。座標が 3〜5m ずれているので、
 *  地図上に2本の平行な線が見える。
 *
 * ─── 解決策 ─────────────────────────────────────────────────────
 *
 *  描画前にジオメトリの「小さな線分（サブエッジ）」を正規化し、
 *  すでに描画済みの線分と近い位置にあるものをスキップする。
 *
 *  (1) 各セグメントのジオメトリを連続する2点ペアに分解
 *  (2) 各ペアの座標を丸めて「グリッドセル」に変換
 *  (3) 方向を無視するために始点・終点を並べ替え（正規化）
 *  (4) Set で重複を検出 → 初出のみ描画
 *
 *  ⚠️ この処理は「描画用」のみ。ルート計算ロジックには一切影響しない。
 */

import { RouteSegment } from '@/types/route';

/**
 * 座標を丸めてグリッドセルに変換する精度
 *
 * 小数点以下4桁 = 0.0001度 ≈ 約11メートル
 * → 双方向車線の間隔（3〜5m）を吸収しつつ、
 *   別の道路（通常 20m 以上離れている）は区別できる
 */
const GRID = 10000; // 1 / 0.0001

/**
 * 座標値を丸める（グリッドに吸着させる）
 *
 * 例: 35.68123456 → 35.6812
 *     小数点以下5桁目以降を切り捨てることで、
 *     数メートルのズレを同じ値にまとめる
 */
function snap(v: number): number {
  return Math.round(v * GRID) / GRID;
}

/**
 * 2点間のサブエッジを「方向を無視した」一意キーに変換する
 *
 * 例:
 *   点A(35.68, 139.70) → 点B(35.69, 139.71) のキー
 *   点B(35.69, 139.71) → 点A(35.68, 139.70) のキー
 *   → 両方とも同じキーになる（A→B と B→A は同一道路）
 *
 * 手順:
 *   1. 両端の座標を丸める
 *   2. 「緯度が小さい方」を先にする（同じなら経度で比較）
 *   3. "小さい側の座標|大きい側の座標" の文字列を返す
 */
function edgeKey(
  a: [number, number],
  b: [number, number]
): string {
  const a0 = snap(a[0]);
  const a1 = snap(a[1]);
  const b0 = snap(b[0]);
  const b1 = snap(b[1]);

  // 正規化: 小さい座標が先（方向を無視するため）
  if (a0 < b0 || (a0 === b0 && a1 < b1)) {
    return `${a0},${a1}|${b0},${b1}`;
  }
  return `${b0},${b1}|${a0},${a1}`;
}

/**
 * 複数セグメントのジオメトリから重複する線分を除去する
 *
 * ─── 入出力のイメージ ───────────────────────────────────────────
 *
 * 入力: segments = [
 *   { geometry: [A, B, C, D] },     ← 行き（A→B→C→D）
 *   { geometry: [D, C', B', A'] },  ← 帰り（D→C'→B'→A'、座標が微妙にずれている）
 * ]
 *
 * 処理:
 *   行きの A→B, B→C, C→D は初出 → 描画する
 *   帰りの D→C', C'→B', B'→A' は丸めると行きと一致 → スキップ
 *
 * 出力: [
 *   [[A, B, C, D]],  ← 行きはそのまま（連続する線のグループが1つ）
 *   [],               ← 帰りは全部スキップ（描画なし）
 * ]
 *
 * ─── なぜ「グループの配列」を返すのか ───────────────────────────
 *
 * セグメントの途中だけ重複する場合がある:
 *   geometry: [A, B, C, D, E]  ← B→C→D は既出、A→B と D→E は初出
 *   → [[A, B], [D, E]]  ← 途切れた2つの線として返す
 *
 * @param segments - ルートセグメントの配列
 * @returns segments と同じ長さの配列。各要素は「描画すべき連続線のグループ」の配列
 */
export function deduplicateSegmentGeometries(
  segments: RouteSegment[]
): [number, number][][][] {
  /** これまでに出現したサブエッジのキーを記録 */
  const seen = new Set<string>();

  return segments.map((seg) => {
    /** このセグメントから生成される、連続した線のグループ */
    const groups: [number, number][][] = [];

    /** 現在構築中の連続線 */
    let current: [number, number][] = [];

    for (let i = 0; i < seg.geometry.length - 1; i++) {
      const key = edgeKey(seg.geometry[i], seg.geometry[i + 1]);

      if (!seen.has(key)) {
        // ── 初出のサブエッジ → 描画対象 ──
        seen.add(key);
        if (current.length === 0) {
          // グループの最初の点を追加
          current.push(seg.geometry[i]);
        }
        current.push(seg.geometry[i + 1]);
      } else {
        // ── 重複したサブエッジ → スキップ ──
        // 今まで積み上げた連続線があれば確定させる
        if (current.length >= 2) {
          groups.push(current);
        }
        current = []; // 新しいグループを開始する準備
      }
    }

    // 最後のグループを確定
    if (current.length >= 2) {
      groups.push(current);
    }

    return groups;
  });
}
